#!/usr/bin/env python3
"""Generate thermo_lut.h: temperature (x10 C) at every STEP-th ADC code, for linear
interpolation. Also reports the worst-case error versus the float formula."""
import math, sys
B, T0 = 3950.0, 298.15
def t_x10(adc):
    adc = min(max(adc, 1), 4094)
    r = 10000.0 * adc / (4095.0 - adc)
    return (1.0/(1.0/T0 + math.log(r/10000.0)/B) - 273.15) * 10.0
def build(shift):
    step = 1 << shift
    n = 4096 // step + 1
    return [int(round(t_x10(k*step))) for k in range(n)]
def interp(tab, shift, adc):
    step = 1 << shift; i = adc >> shift; f = adc & (step-1)
    a, b = tab[i], tab[i+1]
    return a + ((b - a) * f + (step >> 1 if (b-a)*f >= 0 else -(step >> 1))) // step if False else a + (((b - a) * f) // step)
if __name__ == "__main__":
    for shift in (6, 5, 4):
        tab = build(shift)
        err = max(abs(interp(tab, shift, a) - t_x10(a)) for a in range(142, 3996))
        print("shift %d (step %d): %d entries, %d bytes, max err %.2f (x0.1C)" % (shift, 1<<shift, len(tab), 2*len(tab), err))
    shift = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    tab = build(shift)
    with open("v3_optimized/thermo_lut.h", "w") as f:
        f.write("/* generated by tools/gen_lut.py -- do not edit */\n#define LUT_SHIFT %d\n#define LUT_N %d\n" % (shift, len(tab)))
        f.write("static const int16_t g_lut[LUT_N] = {\n")
        for k in range(0, len(tab), 12): f.write("  " + ",".join(str(x) for x in tab[k:k+12]) + ",\n")
        f.write("};\n")
