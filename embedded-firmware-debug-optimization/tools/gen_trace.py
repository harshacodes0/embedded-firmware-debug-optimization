#!/usr/bin/env python3
"""Generate a deterministic 12-bit ADC trace for a 10k NTC thermistor (B=3950)
in a 10k divider (NTC on the low side), with injected sensor faults.
Outputs: common/adc_trace.h and results/trace_truth.csv"""
import math, random, csv, os
N = 512
B, R0, T0, RP, FS = 3950.0, 10000.0, 298.15, 10000.0, 4095
def ntc_r(tc):   return R0 * math.exp(B * (1.0/(tc+273.15) - 1.0/T0))
def adc_of(tc):  r = ntc_r(tc); return FS * r / (r + RP)
def temp_profile(i):
    if i < 300:  # slow warm-up from -8 C to 52 C
        return -8.0 + 60.0 * (1 - math.cos(math.pi * i / 300.0)) / 2.0
    if i < 340:  return 52.0
    return 52.0 - 37.0 * (1 - math.cos(math.pi * (i-340) / (N-340.0))) / 2.0
os.makedirs("results", exist_ok=True)
random.seed(7)
FAULTS = {150: 4095, 330: 0}     # open-circuit, short-circuit
adc, truth = [], []
for i in range(N):
    t = temp_profile(i)
    v = int(round(adc_of(t) + random.gauss(0, 1.5)))
    v = max(1, min(4094, v))
    if i in FAULTS: v = FAULTS[i]
    adc.append(v); truth.append(t)
with open("common/adc_trace.h", "w") as f:
    f.write("/* generated by tools/gen_trace.py -- do not edit */\n#ifndef ADC_TRACE_H\n#define ADC_TRACE_H\n#include <stdint.h>\n")
    f.write("#define TRACE_LEN %d\nstatic const uint16_t g_adc_trace[TRACE_LEN] = {\n" % N)
    for k in range(0, N, 12):
        f.write("  " + ",".join(str(x) for x in adc[k:k+12]) + ",\n")
    f.write("};\n#endif\n")
with open("results/trace_truth.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(["i","adc","true_c"])
    for i in range(N): w.writerow([i, adc[i], "%.3f" % truth[i]])
print("trace ok: min adc", min(a for a in adc if a not in (0,4095)), "max", max(a for a in adc if a not in (0,4095)))
